(function () {
  "use strict";

  /* ---------- Cache-bust the resume PDF download links ----------
     These files get regenerated by CI whenever the résumé content
     changes, but GitHub Pages serves them with a 4-hour max-age and
     the links carry no version query string, so a browser that has
     downloaded one before can silently keep serving the stale copy
     for hours. Appending a fresh query string on every page load
     forces a real fetch instead of a cache hit. */
  document.querySelectorAll(".resume-downloads a[download]").forEach(function (a) {
    var base = a.getAttribute("href").split("?")[0];
    a.setAttribute("href", base + "?v=" + Date.now());
  });

  /* ---------- Notice when this page is a stale build ----------
     The ?v= stamp on style.css and app.js only helps a browser that has
     already fetched today's HTML. The HTML itself is cached too (GitHub
     Pages serves it with max-age=600, and a browser's own heuristics can
     stretch that further), so someone can sit on an old page that keeps
     asking for the old assets by name and never learns a deploy happened.

     CI writes the stamp it used into /version.json, uncached. This script
     knows its own stamp from its src, so comparing the two answers "am I
     the current build?" directly. When they disagree, refetching the page
     with cache: "reload" replaces the stale entry in the HTTP cache -- a
     plain location.reload() would just re-read it -- and then the reload
     lands on the new HTML.

     Guarded by a per-version sessionStorage flag so a bad deploy or a
     half-published version.json can cost at most one reload rather than
     trapping the tab in a loop. Everything is best-effort: no fetch, no
     stamp, a 404, or private-mode storage all mean do nothing. */
  var thisScript = document.currentScript;
  if (window.fetch && thisScript) {
    var stamp = /[?&]v=([^&]+)/.exec(thisScript.src || "");
    if (stamp) {
      fetch("/version.json", { cache: "no-store" }).then(function (res) {
        return res.ok ? res.json() : null;
      }).then(function (data) {
        if (!data || !data.v || data.v === stamp[1]) { return; }
        var flag = "build-reload:" + data.v;
        try {
          if (sessionStorage.getItem(flag)) { return; }
          sessionStorage.setItem(flag, "1");
        } catch (e) { return; }
        fetch(window.location.href, { cache: "reload" }).then(function () {
          window.location.reload();
        }, function () {
          window.location.reload();
        });
      }, function () {});
    }
  }


  /* ---------- Scroll with weight ----------
     A wheel notch is a step function: the browser is handed ~100px and moves
     the page there over a fixed, short animation of its own. Read a long page
     that way and the motion is a series of small shoves — there is nothing
     between where you were and where you land, so the eye has to re-find its
     place after every notch. Trackpads make it worse, not better: they fire
     dozens of tiny deltas a second and each one is its own little jump.

     So the wheel stops driving the page directly. It drives a TARGET, and a
     single requestAnimationFrame loop walks the real scroll position toward
     that target on every frame the display offers — 60, 120, whatever the
     panel does. The reader's own inertia arrives as more target, so flicks
     accumulate instead of fighting, and when the fingers stop the page keeps
     going and settles rather than stopping dead.

     The step is exponential damping, not a fixed-duration tween:

         position += (target - position) * (1 - e^(-lambda * dt))

     Two reasons for that shape. It has no end time, so a new delta mid-glide
     just moves the target and the motion stays continuous — a tween would
     have to be restarted, which is the stutter that makes most "smooth
     scroll" scripts feel worse than none. And because dt is real elapsed
     time, the curve is identical at any refresh rate: the same gesture takes
     the same time on a 60Hz panel and a 120Hz one, the faster panel simply
     draws more of it. (This is the same integrator Lenis and friends settle
     on; the shape is worth borrowing, the 3kb of library is not.)

     What is deliberately NOT touched:
       - touch. Native touch scrolling is already momentum-based, runs on the
         compositor thread, and carries the rubber band, the address-bar hide
         and pull-to-refresh with it. Re-implementing it in JS trades all of
         that for input lag. There are no touch handlers here at all.
       - anything the reader drives directly: scrollbar drags, find-in-page,
         focus jumps, the language hand-off. Any scroll we did not write
         cancels the glide on the next frame and hands the page back.
       - inner scrollers (the playlist, the lab strip on phones), the pinch
         gesture, horizontal swipes, and the ends of the page, where letting
         the event through is what keeps the platform's overscroll alive.
       - reduced motion. Then this whole block is inert and the browser's own
         scrolling is what you get. */
  (function inertialScroll() {
    var docEl = document.documentElement;
    if (!window.requestAnimationFrame) { return; }
    if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) { return; }

    /* Rate of approach, per second. Time to cover 90% of the remaining gap is
       ln(10)/LAMBDA: at 7.5 that is ~0.3s, which is long enough to read as
       weight and short enough that the page still feels attached to the hand.
       Lower is floatier, higher is snappier; below ~5 it starts to feel like
       the page is being towed. */
    var LAMBDA = 7.5;
    var LINE = 34;        /* px per line, for the browsers that report lines */
    var SETTLE = 0.08;    /* px: closer than this and the glide is over */

    var target = 0;
    var position = 0;
    var written = -1;     /* the last position WE asked for */
    var running = false;
    var lastT = 0;
    var maxY = 0;

    function readMax() {
      maxY = Math.max(0, docEl.scrollHeight - window.innerHeight);
      return maxY;
    }
    function clamp(v) { return v < 0 ? 0 : (v > maxY ? maxY : v); }
    function now() { return window.pageYOffset || docEl.scrollTop || 0; }

    function frame(t) {
      var dt = lastT ? (t - lastT) / 1000 : 1 / 60;
      lastT = t;
      /* a tab that was hidden, or a frame the browser had to skip, must not
         be paid off in one enormous step */
      if (dt > 0.05) { dt = 0.05; }

      var real = now();
      if (Math.abs(real - written) > 2) {
        /* somebody else moved the page. Whoever it was outranks us. */
        running = false;
        lastT = 0;
        written = -1;
        return;
      }
      readMax();
      target = clamp(target);

      var gap = target - position;
      if (gap > -SETTLE && gap < SETTLE) {
        position = target;
        window.scrollTo(0, position);
        running = false;
        lastT = 0;
        written = -1;
        return;
      }
      position += gap * (1 - Math.exp(-LAMBDA * dt));
      written = position;
      window.scrollTo(0, position);
      window.requestAnimationFrame(frame);
    }

    function push(delta) {
      readMax();
      if (!running) {
        position = now();
        target = position;
      }
      var next = clamp(target + delta);
      /* Nothing left in that direction: hand the event back to the browser so
         the platform's own end-of-page feel (the rubber band, the overscroll
         glow) still happens. The comparison has to carry a tolerance, because
         once the page is resting on an edge the real offset is usually a
         fraction of a pixel away from it and an exact test never fires. */
      if (Math.abs(next - target) < 1) { return false; }
      target = next;
      if (!running) {
        running = true;
        lastT = 0;
        written = position;
        window.requestAnimationFrame(frame);
      }
      return true;
    }

    /* Does the pointer sit over something that scrolls on its own and still
       has room to move the way the wheel is asking? Then it is not ours. */
    function innerScroller(node, delta) {
      while (node && node !== document.body && node !== docEl) {
        if (node.nodeType === 1 && node.scrollHeight - node.clientHeight > 1) {
          var flow = window.getComputedStyle(node).overflowY;
          if (flow === "auto" || flow === "scroll") {
            var room = delta < 0
              ? node.scrollTop > 1
              : node.scrollTop < node.scrollHeight - node.clientHeight - 1;
            if (room) { return true; }
          }
        }
        node = node.parentNode;
      }
      return false;
    }

    window.addEventListener("wheel", function (e) {
      /* ctrl/cmd + wheel is zoom, and a trackpad pinch arrives as exactly
         that; a sideways gesture is a swipe, sometimes the back gesture */
      if (e.ctrlKey || e.metaKey || e.defaultPrevented) { return; }
      if (Math.abs(e.deltaX) > Math.abs(e.deltaY)) { return; }
      var delta = e.deltaY;
      if (!delta) { return; }
      if (e.deltaMode === 1) { delta *= LINE; }
      else if (e.deltaMode === 2) { delta *= window.innerHeight * 0.9; }
      if (innerScroller(e.target, delta)) { return; }
      /* push() reports false at the top and the bottom of the page, and the
         event goes through untouched so the platform can rubber-band */
      if (push(delta)) { e.preventDefault(); }
    }, { passive: false });

    var TYPING = /^(INPUT|TEXTAREA|SELECT)$/;
    window.addEventListener("keydown", function (e) {
      if (e.defaultPrevented || e.ctrlKey || e.metaKey || e.altKey) { return; }
      var el = e.target;
      if (el && (TYPING.test(el.tagName) || el.isContentEditable)) { return; }
      var page = window.innerHeight * 0.9;
      var key = e.key;
      var delta = null;
      if (key === "PageDown") { delta = page; }
      else if (key === "PageUp") { delta = -page; }
      else if (key === "ArrowDown") { delta = 110; }
      else if (key === "ArrowUp") { delta = -110; }
      else if (key === " " || key === "Spacebar") {
        /* space belongs to whatever is focused if that thing can take it */
        if (el && el.closest && el.closest("a, button, summary, [tabindex]")) { return; }
        delta = e.shiftKey ? -page : page;
      } else if (key === "Home" || key === "End") {
        readMax();
        if (!running) { position = now(); }
        target = key === "Home" ? 0 : maxY;
        if (Math.abs(target - position) < 1) { return; }
        e.preventDefault();
        if (!running) {
          running = true;
          lastT = 0;
          written = position;
          window.requestAnimationFrame(frame);
        }
        return;
      }
      if (delta === null) { return; }
      if (innerScroller(el, delta)) { return; }
      if (push(delta)) { e.preventDefault(); }
    });

    /* html { scroll-behavior: smooth } would put a second animation between
       every scrollTo above and the pixels, i.e. one animation per frame */
    docEl.classList.add("has-inertia");
  })();

  var revealObserver;
  function observeReveals() {
    if (!revealObserver) {
      revealObserver = new IntersectionObserver(function (entries) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            revealObserver.unobserve(entry.target);
          }
        });
      }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
    }
    document.querySelectorAll(".reveal:not(.is-visible)").forEach(function (t) { revealObserver.observe(t); });
  }
  observeReveals();

  var yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  /* ---------- Labradorescence sheen: gentle mouse-follow highlight ---------- */
  var reduceMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var card = document.querySelector(".hero__card");
  if (card && !reduceMotion && window.matchMedia("(hover: hover)").matches) {
    card.addEventListener("mouseenter", function () {
      card.style.animationPlayState = "paused";
    });
    card.addEventListener("mousemove", function (e) {
      var rect = card.getBoundingClientRect();
      var x = ((e.clientX - rect.left) / rect.width) * 100;
      var y = ((e.clientY - rect.top) / rect.height) * 100;
      card.style.setProperty("--mx", x + "%");
      card.style.setProperty("--my", y + "%");
    });
    card.addEventListener("mouseleave", function () {
      card.style.animationPlayState = "running";
    });
  }

  /* ---------- Gregorian -> Jalali (Persian) calendar conversion ----------
     Small self-contained implementation (no external library needed). */
  function gregorianToJalali(gy, gm, gd) {
    var g_d_m = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
    var jy = (gy <= 1600) ? 0 : 979;
    gy -= (gy <= 1600) ? 621 : 1600;
    var gy2 = (gm > 2) ? (gy + 1) : gy;
    var days = (365 * gy) + (Math.floor((gy2 + 3) / 4)) - (Math.floor((gy2 + 99) / 100)) +
      (Math.floor((gy2 + 399) / 400)) - 80 + gd + g_d_m[gm - 1];
    jy += 33 * Math.floor(days / 12053);
    days %= 12053;
    jy += 4 * Math.floor(days / 1461);
    days %= 1461;
    if (days > 365) {
      jy += Math.floor((days - 1) / 365);
      days = (days - 1) % 365;
    }
    var jm, jd;
    if (days < 186) {
      jm = 1 + Math.floor(days / 31);
      jd = 1 + (days % 31);
    } else {
      jm = 7 + Math.floor((days - 186) / 30);
      jd = 1 + ((days - 186) % 30);
    }
    return [jy, jm, jd];
  }

  var jalaliMonths = ["فروردین","اردیبهشت","خرداد","تیر","مرداد","شهریور","مهر","آبان","آذر","دی","بهمن","اسفند"];
  var faDigits = ["۰","۱","۲","۳","۴","۵","۶","۷","۸","۹"];
  function toFaDigits(n) {
    return String(n).replace(/[0-9]/g, function (d) { return faDigits[+d]; });
  }

  /* ---------- Automatic "last updated" date, from GitHub commit history ----------
     Every element carrying data-updated-path gets filled in, so the resume
     page header and the Resume button in the homepage hero read the same
     commit date without either one hard-coding it. data-updated-style picks
     the wording: the full sentence for the page header, a compact form for
     the button. The answer is cached per session, so moving between the two
     pages costs one API call rather than one per page view. */
  var updatedEls = document.querySelectorAll("[data-updated-path]");
  if (updatedEls.length) {
    var lang = document.body.classList.contains("lang-fa") ? "fa" : "en";

    var renderUpdated = function (el, iso) {
      var d = new Date(iso);
      var compact = el.getAttribute("data-updated-style") === "compact";

      if (lang === "fa") {
        var j = gregorianToJalali(d.getFullYear(), d.getMonth() + 1, d.getDate());
        var shamsi = toFaDigits(j[2]) + " " + jalaliMonths[j[1] - 1] + " " + toFaDigits(j[0]);
        if (compact) {
          el.textContent = "آخرین ویرایش: " + shamsi;
        } else {
          /* The Gregorian date is a Latin run sitting in an RTL sentence between
             a parenthesis and a Persian word. As plain text the bidi algorithm
             resolves the day number and the neutrals around it against the
             paragraph's RTL direction, and the parts of the date come apart —
             "3 September 2026" rendering with the day on the wrong side.
             <bdi dir="ltr"> makes it one atomic LTR island, which is exactly
             what the ISBNs and document IDs on this page already do. */
          var miladi = d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
          var bdi = document.createElement("bdi");
          bdi.setAttribute("dir", "ltr");
          bdi.textContent = miladi;
          el.textContent = "آخرین ویرایش: " + shamsi + " (";
          el.appendChild(bdi);
          el.appendChild(document.createTextNode(" میلادی)"));
        }
      } else {
        var en = d.toLocaleDateString("en-US", compact
          ? { day: "numeric", month: "short", year: "numeric" }
          : { day: "numeric", month: "long", year: "numeric" });
        el.textContent = (compact ? "Updated " : "Last updated: ") + en;
      }
    };

    var byPath = {};
    Array.prototype.forEach.call(updatedEls, function (el) {
      var p = el.getAttribute("data-updated-path");
      if (!p) return;
      (byPath[p] = byPath[p] || []).push(el);
    });

    Object.keys(byPath).forEach(function (repoPath) {
      var targets = byPath[repoPath];
      var cacheKey = "last-updated:" + repoPath;
      var cached = null;
      try { cached = sessionStorage.getItem(cacheKey); } catch (e) { /* private mode */ }
      if (cached) {
        targets.forEach(function (el) { renderUpdated(el, cached); });
        return;
      }

      var apiUrl = "https://api.github.com/repos/amini-aria/amini-aria.github.io/commits?path=" +
        encodeURIComponent(repoPath) + "&page=1&per_page=1";

      fetch(apiUrl, { headers: { Accept: "application/vnd.github+json" } })
        .then(function (res) { if (!res.ok) throw new Error("api error"); return res.json(); })
        .then(function (data) {
          if (!data || !data[0] || !data[0].commit) return;
          var iso = data[0].commit.committer.date;
          try { sessionStorage.setItem(cacheKey, iso); } catch (e) { /* quota / private mode */ }
          targets.forEach(function (el) { renderUpdated(el, iso); });
        })
        .catch(function () {
          targets.forEach(function (el) { el.textContent = ""; });
        });
    });
  }

  /* ---------- Publications page: auto-mirror sections from the resume page ----------
     Single source of truth stays the resume page. This just fetches its HTML
     (same-origin) and clones the matching .resume__block sections in place,
     so nothing has to be typed twice. */
  var mirrorMount = document.getElementById("mirror-mount");
  if (mirrorMount) {
    var sourcePath = mirrorMount.getAttribute("data-source");
    var titlesAttr = mirrorMount.getAttribute("data-titles") || "";
    var wantedTitles = titlesAttr.split("|").map(function (s) { return s.trim(); });

    /* The page head already started this request (and may have answered it
       from the session cache), so prefer that over issuing a second one. */
    var preloaded = window.__mirrorSource;
    var source = preloaded && preloaded.url === sourcePath
      ? preloaded.text
      : fetch(sourcePath).then(function (res) {
          if (!res.ok) throw new Error("fetch failed");
          return res.text();
        });

    source
      .then(function (html) {
        var doc = new DOMParser().parseFromString(html, "text/html");
        var blocks = doc.querySelectorAll(".resume__block");
        var found = 0;
        /* collect into a fragment first: appending block by block would lay
           the page out once per section */
        var frag = document.createDocumentFragment();
        blocks.forEach(function (block) {
          var titleEl = block.querySelector(".resume__block-title");
          if (!titleEl) return;
          var title = titleEl.textContent.trim();
          if (wantedTitles.indexOf(title) !== -1) {
            var clone = block.cloneNode(true);
            clone.classList.add("reveal");
            frag.appendChild(clone);
            found++;
          }
        });
        mirrorMount.appendChild(frag);
        if (found === 0) {
          mirrorMount.innerHTML = '<p class="section__text">' + mirrorMount.getAttribute("data-empty-text") + "</p>";
        } else {
          observeReveals();
        }
      })
      .catch(function () {
        mirrorMount.innerHTML = '<p class="section__text">' + mirrorMount.getAttribute("data-error-text") + "</p>";
      });
  }
    /* ---------- Contact page: shingled card deck ----------
     Each card carries its own resting tilt and paint order (--rot/--z, set
     inline per card in the HTML). pointerdown brings a card forward
     (.is-front) BEFORE the link resolves, so a touch user actually sees the
     lift; the keyboard gets the same state from :focus-visible in CSS with no
     JS at all. No preventDefault anywhere — the links must keep working, and
     that is safe because nothing is hidden behind a tap. */
  var contactCards = document.querySelectorAll(".contact-card");
  if (contactCards.length) {
    var frontCard = null;
    var bringForward = function (el) {
      if (frontCard === el) { return; }
      if (frontCard) { frontCard.classList.remove("is-front"); }
      el.classList.add("is-front");
      frontCard = el;
    };
    var clearFront = function () {
      if (frontCard) { frontCard.classList.remove("is-front"); frontCard = null; }
    };
    Array.prototype.forEach.call(contactCards, function (el) {
      el.addEventListener("pointerdown", function () { bringForward(el); });
      el.addEventListener("click", function () { bringForward(el); });
      el.addEventListener("pointercancel", clearFront);
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" || e.keyCode === 27) { clearFront(); }
    });
  }

  /* ---------- Spotify playlist shutter ---------- */
  var spotifyToggle = document.getElementById("spotify-toggle");
  var spotifyDropdown = document.getElementById("spotify-dropdown");
  var spotifyScrollInner = document.getElementById("spotify-scroll-inner");
  var spotifyScrollThumb = document.getElementById("spotify-scroll-thumb");
  var heroEl = document.querySelector(".hero");
  function updateSpotifyThumb() {
    if (!spotifyScrollInner || !spotifyScrollThumb) return;
    var track = spotifyScrollInner.previousElementSibling;
    var trackH = track ? track.clientHeight : spotifyScrollInner.clientHeight;
    var ratio = spotifyScrollInner.clientHeight / spotifyScrollInner.scrollHeight;
    if (!isFinite(ratio) || ratio >= 1) { spotifyScrollThumb.style.display = "none"; return; }
    spotifyScrollThumb.style.display = "block";
    var thumbH = Math.max(18, trackH * ratio);
    var maxScroll = spotifyScrollInner.scrollHeight - spotifyScrollInner.clientHeight;
    var scrollFrac = maxScroll > 0 ? spotifyScrollInner.scrollTop / maxScroll : 0;
    var thumbTop = scrollFrac * (trackH - thumbH);
    spotifyScrollThumb.style.height = thumbH + "px";
    spotifyScrollThumb.style.top = thumbTop + "px";
  }
  /* The list fades out at whichever edge still has rows behind it. Without
     this the first and last row would always look half-erased, which reads as
     a rendering fault rather than as an affordance. */
  var spotifyWrap = document.querySelector(".spotify-scroll-wrap");
  function updateSpotifyFades() {
    if (!spotifyWrap || !spotifyScrollInner) return;
    var maxScroll = spotifyScrollInner.scrollHeight - spotifyScrollInner.clientHeight;
    var top = spotifyScrollInner.scrollTop;
    spotifyWrap.classList.toggle("at-top", top <= 1);
    spotifyWrap.classList.toggle("at-end", maxScroll <= 1 || top >= maxScroll - 1);
  }
  /* The header count is derived from the list itself, so adding or removing a
     playlist can never leave the two disagreeing. Only the digits are written;
     the word beside them stays in the page, in whichever language it is. */
  (function syncPlaylistCount() {
    var slot = document.querySelector("[data-playlist-count]");
    var rows = document.querySelectorAll(".spotify-panel__list a");
    if (!slot || !rows.length) return;
    var n = String(rows.length);
    if (document.body.classList.contains("lang-fa")) {
      var fa = "\u06F0\u06F1\u06F2\u06F3\u06F4\u06F5\u06F6\u06F7\u06F8\u06F9";
      n = n.replace(/[0-9]/g, function (d) { return fa.charAt(Number(d)); });
    }
    slot.textContent = n;
  })();
  function updateSpotifyScrollUI() { updateSpotifyThumb(); updateSpotifyFades(); }
  if (spotifyScrollInner) {
    spotifyScrollInner.addEventListener("scroll", updateSpotifyScrollUI);
    window.addEventListener("resize", updateSpotifyScrollUI);
    updateSpotifyFades();
  }
  /* The visual scrollbar is custom, so make its thumb behave like a real
     scrollbar as well: click-to-jump and pointer drag both update the list. */
  var spotifyTrack = document.querySelector(".spotify-scrollbar-track");
  if (spotifyTrack && spotifyScrollInner && spotifyScrollThumb) {
    var dragState = null;
    function scrollFromPointer(clientY) {
      var trackRect = spotifyTrack.getBoundingClientRect();
      var thumbRect = spotifyScrollThumb.getBoundingClientRect();
      var maxTop = Math.max(1, trackRect.height - thumbRect.height);
      var top = Math.min(maxTop, Math.max(0, clientY - trackRect.top - (dragState ? dragState.grab : thumbRect.height / 2)));
      var maxScroll = spotifyScrollInner.scrollHeight - spotifyScrollInner.clientHeight;
      spotifyScrollInner.scrollTop = maxScroll * (top / maxTop);
    }
    spotifyScrollThumb.addEventListener("pointerdown", function (e) {
      if (spotifyScrollThumb.style.display === "none") return;
      e.preventDefault();
      dragState = { grab: e.clientY - spotifyScrollThumb.getBoundingClientRect().top };
      spotifyScrollThumb.setPointerCapture(e.pointerId);
      spotifyScrollThumb.classList.add("is-dragging");
    });
    spotifyScrollThumb.addEventListener("pointermove", function (e) {
      if (dragState) scrollFromPointer(e.clientY);
    });
    function stopSpotifyDrag() {
      dragState = null;
      spotifyScrollThumb.classList.remove("is-dragging");
    }
    spotifyScrollThumb.addEventListener("pointerup", stopSpotifyDrag);
    spotifyScrollThumb.addEventListener("pointercancel", stopSpotifyDrag);
    spotifyTrack.addEventListener("pointerdown", function (e) {
      if (e.target === spotifyScrollThumb || spotifyScrollThumb.style.display === "none") return;
      dragState = null;
      scrollFromPointer(e.clientY);
    });
  }
  function closeSpotify() {
    if (spotifyDropdown) spotifyDropdown.classList.remove("is-open");
    if (spotifyToggle) spotifyToggle.setAttribute("aria-expanded", "false");
    if (heroEl) heroEl.classList.remove("spotify-open");
  }
  if (spotifyToggle && spotifyDropdown) {
    spotifyToggle.addEventListener("click", function (e) {
      e.stopPropagation();
      var open = spotifyDropdown.classList.toggle("is-open");
      spotifyToggle.setAttribute("aria-expanded", open ? "true" : "false");
      if (heroEl) heroEl.classList.toggle("spotify-open", open);
      if (open) { updateSpotifyScrollUI(); setTimeout(updateSpotifyScrollUI, 480); }
    });
    document.addEventListener("click", function (e) {
      if (!spotifyDropdown.contains(e.target)) closeSpotify();
    });
  }
  /* ---------- Marks with nowhere to go ----------
     Three of the profile marks in the hero (Scholar, ResearchGate, GitHub)
     are still waiting on their addresses and carry href="#". A bare "#" is a
     link to the top of the document, so pressing one threw the reader back
     to the top of the page — the one thing a dead link should not do. Until
     the real addresses land they announce themselves as unavailable and do
     nothing at all. */
  Array.prototype.forEach.call(
    document.querySelectorAll('.hero__socials a[href="#"]'),
    function (a) {
      a.setAttribute("aria-disabled", "true");
      a.addEventListener("click", function (e) { e.preventDefault(); });
    }
  );

  /* ---------- One highlight, travelling ----------
     Every dock item used to fade in its own background on hover. Two
     rectangles cross-fading reads as two events; one rectangle moving reads
     as a single continuous gesture, which is the difference between a bar
     that feels switchy and one that feels smooth. The element is created
     here rather than sitting in all eight pages' markup, and only where a
     real pointer exists — on touch there is no hover to follow, and the CSS
     fallback (guarded by :has(.dock__glow)) takes over by itself. */
  var dockEl = document.querySelector(".dock");
  if (dockEl && window.matchMedia && window.matchMedia("(hover: hover) and (pointer: fine)").matches) {
    var glow = document.createElement("span");
    glow.className = "dock__glow";
    glow.setAttribute("aria-hidden", "true");
    dockEl.insertBefore(glow, dockEl.firstChild);

    var moveGlow = function (el) {
      var d = dockEl.getBoundingClientRect();
      var r = el.getBoundingClientRect();
      glow.style.width = r.width + "px";
      glow.style.height = r.height + "px";
      glow.style.transform = "translate(" + (r.left - d.left) + "px, " + (r.top - d.top) + "px)";
      dockEl.classList.add("is-hovering");
    };
    var hideGlow = function () { dockEl.classList.remove("is-hovering"); };

    Array.prototype.forEach.call(dockEl.querySelectorAll(".dock__item"), function (el) {
      el.addEventListener("mouseenter", function () { moveGlow(el); });
      el.addEventListener("focus", function () { moveGlow(el); });
    });
    dockEl.addEventListener("mouseleave", hideGlow);
    dockEl.addEventListener("focusout", hideGlow);
    /* the bar is centred, so its items move under a resize; a stale transform
       would leave the highlight parked beside the item it belongs to */
    window.addEventListener("resize", hideGlow);
  }

  /* ---------- The language plate is one target, not two ----------
     The switch lives in the dock as two stacked 17px rows. That is a smaller
     target than a fingertip, and half of it used to be a no-op: pressing the
     row you were already on did nothing. The plate itself now takes the
     click and always resolves to the OTHER language, so anywhere inside it
     — either row, the gap, or the margin the ::after overlay adds past its
     edge — switches. The real link is still there and still navigates on its
     own for keyboard and middle-click; the handler only steps in when the
     press landed anywhere else.

     .lang-pill, which this used to be bound to, was the header's language
     control and went away with the header — the scroll-position hand-off had
     been silently dead since. */
  function rememberScroll() {
    var docH = document.documentElement.scrollHeight - window.innerHeight;
    var ratio = docH > 0 ? window.scrollY / docH : 0;
    try { sessionStorage.setItem("scrollRatio", String(ratio)); } catch (e) {}
  }
  var langPlate = document.querySelector(".dock-lang");
  if (langPlate) {
    var otherLang = langPlate.querySelector("a:not(.is-active)");
    if (otherLang) {
      langPlate.addEventListener("click", function (e) {
        if (e.button || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) { return; }
        rememberScroll();
        if (e.target.closest && e.target.closest("a") === otherLang) { return; }
        e.preventDefault();
        window.location.href = otherLang.href;
      });
    }
  }
  /* The hand-off itself. One requestAnimationFrame was not enough and the
     feature was silently doing nothing: at that point the new page is a
     fraction of its final height — fonts still swapping, images still
     arriving — so the ratio resolved against almost no page, and whatever
     little scroll it did ask for was then overwritten by the browser's own
     reset for a fresh navigation. So hold the position instead of setting
     it: re-place it every frame while the page is still growing, and give
     that up the moment the reader touches anything, because from then on
     where the page sits is their business and not ours. */
  (function restoreScroll() {
    var val;
    try { val = sessionStorage.getItem("scrollRatio"); } catch (e) { val = null; }
    if (val === null) return;
    try { sessionStorage.removeItem("scrollRatio"); } catch (e) {}
    var ratio = parseFloat(val);
    if (isNaN(ratio) || ratio <= 0) return;

    var giveUpAt = Date.now() + 1800;
    var events = ["wheel", "touchstart", "pointerdown", "keydown"];
    var live = true;

    function stop() {
      live = false;
      events.forEach(function (name) { window.removeEventListener(name, stop); });
    }
    function place() {
      if (!live) return;
      var docH = document.documentElement.scrollHeight - window.innerHeight;
      if (docH > 0) window.scrollTo(0, Math.round(docH * ratio));
      if (Date.now() > giveUpAt) { stop(); return; }
      requestAnimationFrame(place);
    }
    events.forEach(function (name) {
      window.addEventListener(name, stop, { passive: true });
    });
    place();
  })();
  /* Aria's Lab title typewriter, card rendering, and terminal log now live
     in assets/js/lab.js (single source of truth for that section). */

})();
