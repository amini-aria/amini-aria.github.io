/* =============================================================================
   HERO PORTRAIT MORPH — one continuous shape, not two crossfading layers.

   The frame around the portrait photo IS the clip mask around the photo:
   the exact same <path> data drives both the visible stroked border and
   the clip-path, so when the border's shape animates from a soft living
   blob into the precise outer silhouette of an ammonite shell, the photo
   window changes shape right along with it — there is no separate "photo
   layer" and "ammonite layer" swapped by a crossfade; it's one boundary
   morphing, with the ammonite's internal shell detail (inner spiral +
   growth ribs) fading in only once the boundary has actually become that
   shape.

   HERO_MORPH_BLOB / HERO_MORPH_AMMONITE (both 120 matching points, same
   mean radius so the morph doesn't change the frame's overall size) and
   HERO_AMMONITE_INNER / HERO_AMMONITE_RIBS come from hero-portrait-data.js
   (generated by scripts/gen_hero_ammonite.py from the real logarithmic
   growth spiral ammonite shells actually grow along).
   ============================================================================= */
(function () {
  "use strict";

  var clipPath = document.getElementById("portrait-clip-path");
  var framePath = document.getElementById("portrait-frame-path");
  var detailGroup = document.querySelector(".hero__ammonite-detail");
  var photoImg = document.querySelector(".hero__portrait-photo-img");
  if (!clipPath || !framePath) return;

  var reduceMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  function pathFromPoints(pts) {
    var d = "M" + pts[0][0] + "," + pts[0][1];
    for (var i = 1; i < pts.length; i++) d += " L" + pts[i][0] + "," + pts[i][1];
    return d + " Z";
  }

  function lerpPoints(a, b, t) {
    var out = [];
    for (var i = 0; i < a.length; i++) {
      out.push([a[i][0] + (b[i][0] - a[i][0]) * t, a[i][1] + (b[i][1] - a[i][1]) * t]);
    }
    return out;
  }

  // The resting blob is never perfectly still: it continuously
  // cross-fades between two organic variants on its own slow cycle, so
  // the frame reads as alive even outside the photo<->ammonite morph.
  var WOBBLE_PERIOD = 5200;
  function wobbleBlob(elapsed) {
    var w = (Math.sin((elapsed / WOBBLE_PERIOD) * Math.PI * 2) + 1) / 2;
    return lerpPoints(HERO_MORPH_BLOB, HERO_MORPH_BLOB_B, w);
  }

  function setShape(t, elapsed) {
    var blobNow = wobbleBlob(elapsed);
    var pts = t <= 0 ? blobNow : t >= 1 ? HERO_MORPH_AMMONITE : lerpPoints(blobNow, HERO_MORPH_AMMONITE, t);
    var d = pathFromPoints(pts);
    clipPath.setAttribute("d", d);
    framePath.setAttribute("d", d);
  }

  // ease-in-out cubic, used for both the shape morph and the crossfade
  function ease(x) {
    return x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2;
  }

  if (reduceMotion) {
    setShape(0, 0);
    if (photoImg) photoImg.style.opacity = "1";
    if (detailGroup) detailGroup.style.opacity = "0";
    return;
  }

  // Timeline (ms), one full cycle:
  var HOLD_PHOTO = 4200;
  var MORPH_IN = 1300;
  var HOLD_AMMONITE = 2600;
  var MORPH_OUT = 1300;
  var TOTAL = HOLD_PHOTO + MORPH_IN + HOLD_AMMONITE + MORPH_OUT;

  function phaseAt(elapsed) {
    var e = elapsed % TOTAL;
    if (e < HOLD_PHOTO) return 0;
    e -= HOLD_PHOTO;
    if (e < MORPH_IN) return ease(e / MORPH_IN);
    e -= MORPH_IN;
    if (e < HOLD_AMMONITE) return 1;
    e -= HOLD_AMMONITE;
    return 1 - ease(e / MORPH_OUT);
  }

  var start = performance.now();
  function frame(now) {
    var elapsed = now - start;
    var t = phaseAt(elapsed);
    setShape(t, elapsed);
    if (photoImg) photoImg.style.opacity = String(Math.max(0, 1 - t * 1.6));
    if (detailGroup) detailGroup.style.opacity = String(Math.max(0, t * 1.6 - 0.6));
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
})();
