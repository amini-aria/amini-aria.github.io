/* =============================================================================
   HERO PORTRAIT MORPH — one continuous shape, not two crossfading layers.

   The frame around the portrait photo IS the clip mask around the photo: the
   exact same <path> data drives both the visible stroked border and the
   clip-path, so when the border's shape animates from a soft living blob into
   the outer silhouette of the site's skull mark, the photo window changes
   shape right along with it. There is no separate "photo layer" and "skull
   layer" swapped by a crossfade; it's one boundary morphing, and the skull's
   interior — the eye socket, the nostril, the gaps between the teeth — only
   washes in once the boundary has actually become that shape.

   Because the silhouette keeps every corner of the mark, at the end of the
   morph the frame is tracing the mark itself, and the filled skull sits
   exactly inside it. The stroke thins as it gets there so it sharpens the
   edge instead of clogging the teeth.

   HERO_MORPH_BLOB / HERO_MORPH_BLOB_B / HERO_MORPH_SKULL (all with matching
   point counts, same overall extent so the morph doesn't change the frame's
   size) come from hero-portrait-data.js, generated by
   scripts/gen_hero_portrait.py from the brand mark in the header.
   ============================================================================= */
(function () {
  "use strict";

  var clipPath = document.getElementById("portrait-clip-path");
  var framePath = document.getElementById("portrait-frame-path");
  var skullPath = document.getElementById("portrait-skull-path");
  var photoImg = document.querySelector(".hero__portrait-photo-img");
  if (!clipPath || !framePath) return;

  var reduceMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  var FRAME_STROKE_REST = 1.6;
  var FRAME_STROKE_SKULL = 0.35;

  function pathFromPoints(pts) {
    var parts = new Array(pts.length);
    for (var i = 0; i < pts.length; i++) parts[i] = pts[i][0] + "," + pts[i][1];
    return "M" + parts.join(" L") + " Z";
  }

  function lerpPoints(a, b, t) {
    var out = [];
    for (var i = 0; i < a.length; i++) {
      out.push([a[i][0] + (b[i][0] - a[i][0]) * t, a[i][1] + (b[i][1] - a[i][1]) * t]);
    }
    return out;
  }

  function clamp01(x) { return x < 0 ? 0 : x > 1 ? 1 : x; }

  /* a fade that starts at `from`, finishes at `to`, and eases at both ends —
     linear opacity ramps are what make a crossfade look mechanical */
  function ramp(t, from, to) {
    var x = clamp01((t - from) / (to - from));
    return x * x * (3 - 2 * x);
  }

  // The resting blob is never perfectly still: it continuously cross-fades
  // between two organic variants on its own slow cycle, so the frame reads as
  // alive even outside the photo<->skull morph.
  var WOBBLE_PERIOD = 5200;
  function wobbleBlob(elapsed) {
    var w = (Math.sin((elapsed / WOBBLE_PERIOD) * Math.PI * 2) + 1) / 2;
    return lerpPoints(HERO_MORPH_BLOB, HERO_MORPH_BLOB_B, w);
  }

  function setShape(t, elapsed) {
    var blobNow = wobbleBlob(elapsed);
    var pts = t <= 0 ? blobNow : t >= 1 ? HERO_MORPH_SKULL : lerpPoints(blobNow, HERO_MORPH_SKULL, t);
    var d = pathFromPoints(pts);
    clipPath.setAttribute("d", d);
    framePath.setAttribute("d", d);
  }

  function paint(t) {
    // the photo clears early, so the window is already an empty cream shape
    // by the time the skull arrives in it
    if (photoImg) photoImg.style.opacity = String(1 - ramp(t, 0.05, 0.5));
    if (skullPath) skullPath.style.opacity = String(ramp(t, 0.55, 0.98));
    framePath.style.strokeWidth =
      FRAME_STROKE_REST + (FRAME_STROKE_SKULL - FRAME_STROKE_REST) * ramp(t, 0.45, 1);
  }

  // ease-in-out cubic for the shape morph itself
  function ease(x) {
    return x < 0.5 ? 4 * x * x * x : 1 - Math.pow(-2 * x + 2, 3) / 2;
  }

  if (reduceMotion) {
    setShape(0, 0);
    paint(0);
    return;
  }

  // Timeline (ms), one full cycle:
  var HOLD_PHOTO = 4200;
  var MORPH_IN = 2100;
  var HOLD_SKULL = 4300;
  var MORPH_OUT = 1400;
  var TOTAL = HOLD_PHOTO + MORPH_IN + HOLD_SKULL + MORPH_OUT;

  function phaseAt(elapsed) {
    var e = elapsed % TOTAL;
    if (e < HOLD_PHOTO) return 0;
    e -= HOLD_PHOTO;
    if (e < MORPH_IN) return ease(e / MORPH_IN);
    e -= MORPH_IN;
    if (e < HOLD_SKULL) return 1;
    e -= HOLD_SKULL;
    return 1 - ease(e / MORPH_OUT);
  }

  var start = performance.now();
  function frame(now) {
    var elapsed = now - start;
    var t = phaseAt(elapsed);
    setShape(t, elapsed);
    paint(t);
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
})();
